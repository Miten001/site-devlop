"use strict";
const fs=require('node:fs'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('dashboard.html','utf8');
const dom=new JSDOM(html);const d=dom.window.document;
assert.equal(d.querySelectorAll('#sponsor-smartlink').length,0);
assert.equal(d.querySelectorAll('aside[aria-label="Sponsor advertisement"]').length,0);
assert(!html.includes('https://auctionr.org/4/3b073a576a3ea2f70d17a22f28c21318'));
assert(!d.body.textContent.includes('Visit sponsor'));
assert.equal(d.querySelectorAll('.ff-sponsor-banner').length,1,'Existing banner stays unchanged');
dom.window.close();
console.log('Smartlink removal tests passed: no sponsor button, destination or empty wrapper; existing banner preserved.');
