-- ============================================================
-- FlexFam · DAILY QUESTS & PROFILE BADGES   (#27)
--
--   • 6 Daily Quests (reset every day at 00:00 UTC)
--   • 8 Lifetime Milestones (one-time rewards + unlockable badges)
--   • Server-authoritative verification: progress is computed from
--     real Postgres rows (daily_streaks, market_campaign_subs,
--     job_subs, mining_ledger, referrals, market_campaigns, jobs).
--   • Atomic claim: locks public.balances (for update), verifies
--     progress >= target, prevents duplicate claims via
--     unique (user_id, quest_id, period_key), credits points or USDT,
--     and logs USDT quest rewards to wallet_txns (type = 'quest').
--
-- Safe to re-run (idempotent).
-- RUN ORDER: after #1 (supabase.sql), #2 (supabase-mining.sql),
--            and #3 (supabase-wallet.sql). Optional modules (#5, #14,
--            #16) are detected automatically via to_regclass().
-- ============================================================

-- 0. Ensure prerequisite wallet/balance tables exist
do $$
begin
  if to_regclass('public.balances') is null or to_regclass('public.wallet_txns') is null then
    raise exception 'Run supabase-mining.sql (#2) and supabase-wallet.sql (#3) before supabase-quests-badges.sql (#27).'
      using errcode = 'P0001';
  end if;
end;
$$;

-- 1. Claims table — one row per (user, quest, period)
create table if not exists public.quest_claims (
  id            bigint generated by default as identity primary key,
  user_id       uuid    not null references auth.users(id) on delete cascade,
  quest_id      text    not null,
  period_key    text    not null,          -- 'YYYY-MM-DD' (UTC) for daily, 'lifetime' for milestones
  reward_type   text    not null check (reward_type in ('points', 'usdt')),
  reward_amount numeric not null check (reward_amount > 0),
  claimed_at    timestamptz not null default now(),
  unique (user_id, quest_id, period_key)
);

create index if not exists quest_claims_user_idx
  on public.quest_claims (user_id, period_key, claimed_at desc);

alter table public.quest_claims enable row level security;
-- No direct browser policies — all reads and claims go through security definer RPCs below.

-- ------------------------------------------------------------
-- 2. Internal helper: real activity metrics for a member
-- ------------------------------------------------------------
create or replace function public.quest_user_metrics(p_user uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_day_start       timestamptz := date_trunc('day', now() at time zone 'UTC') at time zone 'UTC';
  v_today_ist       date        := (now() at time zone 'Asia/Kolkata')::date;
  v_today_checkin   int := 0;
  v_today_campaigns int := 0;
  v_today_jobs      int := 0;
  v_today_mining    int := 0;
  v_total_campaigns int := 0;
  v_total_jobs      int := 0;
  v_best_streak     int := 0;
  v_referrals       int := 0;
  v_created_camps   int := 0;
  v_created_jobs    int := 0;
begin
  if to_regclass('public.daily_streaks') is not null then
    select
      case when (d.last_claim_at is not null and d.last_claim_at >= v_day_start)
             or (d.last_date is not null and d.last_date >= v_today_ist)
           then 1 else 0 end,
      greatest(coalesce(d.best, 0), coalesce(d.streak, 0))
      into v_today_checkin, v_best_streak
      from public.daily_streaks d
     where d.user_id = p_user;
    v_today_checkin := coalesce(v_today_checkin, 0);
    v_best_streak   := coalesce(v_best_streak, 0);
  end if;

  if to_regclass('public.market_campaign_subs') is not null then
    select
      count(*) filter (where s.status in ('approved', 'pending') and s.at >= v_day_start),
      count(*) filter (where s.status = 'approved')
      into v_today_campaigns, v_total_campaigns
      from public.market_campaign_subs s
     where s.worker = p_user;
  end if;

  if to_regclass('public.job_subs') is not null then
    select
      count(*) filter (where s.status in ('approved', 'pending') and s.at >= v_day_start),
      count(*) filter (where s.status = 'approved')
      into v_today_jobs, v_total_jobs
      from public.job_subs s
     where s.worker = p_user;
  end if;

  if to_regclass('public.mining_ledger') is not null then
    select count(*)
      into v_today_mining
      from public.mining_ledger m
     where m.user_id = p_user and m.type = 'claim' and m.at >= v_day_start;
  end if;

  if to_regclass('public.referrals') is not null then
    select count(*)
      into v_referrals
      from public.referrals r
     where r.referrer_user = p_user;
  end if;

  if to_regclass('public.market_campaigns') is not null then
    select count(*) into v_created_camps
      from public.market_campaigns c where c.owner = p_user;
  end if;

  if to_regclass('public.jobs') is not null then
    select count(*) into v_created_jobs
      from public.jobs j where j.owner = p_user;
  end if;

  return jsonb_build_object(
    'todayCheckin',   coalesce(v_today_checkin, 0),
    'todayCampaigns', coalesce(v_today_campaigns, 0),
    'todayJobs',      coalesce(v_today_jobs, 0),
    'todayMining',    coalesce(v_today_mining, 0),
    'totalTasks',     coalesce(v_total_campaigns, 0) + coalesce(v_total_jobs, 0),
    'bestStreak',     coalesce(v_best_streak, 0),
    'referrals',      coalesce(v_referrals, 0),
    'createdCount',   coalesce(v_created_camps, 0) + coalesce(v_created_jobs, 0)
  );
end;
$$;

revoke all on function public.quest_user_metrics(uuid) from public, anon, authenticated;

