-- ------------------------------------------------------------
-- 4. quests_state() — member's live quest progress, claims & badges
-- ------------------------------------------------------------
create or replace function public.quests_state()
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_user       uuid        := public.wallet_require_user();
  v_today_key  text        := to_char(now() at time zone 'UTC', 'YYYY-MM-DD');
  v_reset_at   timestamptz := (date_trunc('day', now() at time zone 'UTC') + interval '1 day') at time zone 'UTC';
  v_metrics    jsonb       := public.quest_user_metrics(v_user);
  v_quests     jsonb;
  v_badges     jsonb;
  v_claimed_u  numeric;
  v_claimed_p  numeric;
  v_claim_cnt  int;
begin
  select coalesce(jsonb_agg(jsonb_build_object(
      'id',           q.quest_id,
      'kind',         q.kind,
      'title',        q.title,
      'metric',       q.metric_key,
      'progress',     least(coalesce((v_metrics ->> q.metric_key)::int, 0), q.target),
      'rawProgress',  coalesce((v_metrics ->> q.metric_key)::int, 0),
      'target',       q.target,
      'rewardType',   q.reward_type,
      'rewardAmount', q.reward_amount,
      'badgeId',      q.badge_id,
      'periodKey',    case when q.kind = 'daily' then v_today_key else 'lifetime' end,
      'claimed',      (c.id is not null),
      'claimedAt',    case when c.claimed_at is not null then extract(epoch from c.claimed_at) * 1000 else null end,
      'claimable',    (c.id is null and coalesce((v_metrics ->> q.metric_key)::int, 0) >= q.target)
    )), '[]'::jsonb)
    into v_quests
    from public.quest_catalog() q
    left join public.quest_claims c
      on c.user_id = v_user
     and c.quest_id = q.quest_id
     and c.period_key = case when q.kind = 'daily' then v_today_key else 'lifetime' end;

  select coalesce(jsonb_agg(jsonb_build_object(
      'id',       q.badge_id,
      'questId',  q.quest_id,
      'unlocked', (coalesce((v_metrics ->> q.metric_key)::int, 0) >= q.target or c.id is not null),
      'claimed',  (c.id is not null),
      'progress', least(coalesce((v_metrics ->> q.metric_key)::int, 0), q.target),
      'target',   q.target
    )), '[]'::jsonb)
    into v_badges
    from public.quest_catalog() q
    left join public.quest_claims c
      on c.user_id = v_user and c.quest_id = q.quest_id and c.period_key = 'lifetime'
   where q.badge_id is not null;

  select
    coalesce(sum(reward_amount) filter (where reward_type = 'usdt'), 0),
    coalesce(sum(reward_amount) filter (where reward_type = 'points'), 0),
    count(*)
    into v_claimed_u, v_claimed_p, v_claim_cnt
    from public.quest_claims
   where user_id = v_user;

  return jsonb_build_object(
    'todayKey',   v_today_key,
    'utcResetAt', extract(epoch from v_reset_at) * 1000,
    'metrics',    v_metrics,
    'quests',     v_quests,
    'badges',     v_badges,
    'totals', jsonb_build_object(
      'claims', coalesce(v_claim_cnt, 0),
      'usdt',   round(coalesce(v_claimed_u, 0), 4),
      'points', coalesce(v_claimed_p, 0)
    )
  );
end;
$$;

-- ------------------------------------------------------------
-- 5. quests_claim(p_quest_id) — atomic, server-verified reward claim
-- ------------------------------------------------------------
create or replace function public.quests_claim(p_quest_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_user       uuid := public.wallet_require_user();
  v_today_key  text := to_char(now() at time zone 'UTC', 'YYYY-MM-DD');
  v_q          record;
  v_period_key text;
  v_metrics    jsonb;
  v_progress   int;
begin
  select * into v_q from public.quest_catalog() where quest_id = trim(coalesce(p_quest_id, ''));
  if not found then
    raise exception 'Quest not found' using errcode = 'P0001';
  end if;

  v_period_key := case when v_q.kind = 'daily' then v_today_key else 'lifetime' end;

  -- Lock the member's balance row first so two simultaneous requests serialize cleanly.
  insert into public.balances (user_id) values (v_user) on conflict (user_id) do nothing;
  perform 1 from public.balances where user_id = v_user for update;

  if exists (
    select 1 from public.quest_claims
     where user_id = v_user
       and quest_id = v_q.quest_id
       and period_key = v_period_key
  ) then
    raise exception 'You already claimed this quest reward' using errcode = 'P0001';
  end if;

  v_metrics  := public.quest_user_metrics(v_user);
  v_progress := coalesce((v_metrics ->> v_q.metric_key)::int, 0);
  if v_progress < v_q.target then
    raise exception 'Quest progress is %/% — finish the goal before claiming', v_progress, v_q.target
      using errcode = 'P0001';
  end if;

  insert into public.quest_claims (user_id, quest_id, period_key, reward_type, reward_amount)
  values (v_user, v_q.quest_id, v_period_key, v_q.reward_type, v_q.reward_amount);

  if v_q.reward_type = 'points' then
    update public.balances
       set points = points + round(v_q.reward_amount)::bigint,
           updated_at = now()
     where user_id = v_user;
  else
    update public.balances
       set usdt = round(usdt + v_q.reward_amount, 8),
           total_earned = round(total_earned + v_q.reward_amount, 8),
           updated_at = now()
     where user_id = v_user;

    perform public.wallet_tx(
      v_user,
      'quest',
      v_q.reward_amount,
      'Quest reward: ' || v_q.title,
      'completed',
      null,
      null
    );
  end if;

  return jsonb_build_object(
    'claimed', jsonb_build_object(
      'id',           v_q.quest_id,
      'title',        v_q.title,
      'rewardType',   v_q.reward_type,
      'rewardAmount', v_q.reward_amount,
      'badgeId',      v_q.badge_id
    ),
    'state', public.quests_state()
  );
end;
$$;

revoke all on function public.quests_state()     from public, anon;
revoke all on function public.quests_claim(text) from public, anon;
grant execute on function public.quests_state()     to authenticated;
grant execute on function public.quests_claim(text) to authenticated;

notify pgrst, 'reload schema';
